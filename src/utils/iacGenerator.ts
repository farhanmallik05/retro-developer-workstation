export interface ArchitectureNodeData {
  id: string;
  type: string;
  label: string;
  category: string;
}

export interface ArchitectureEdgeData {
  from: string;
  to: string;
}

/**
 * Generates production-ready AWS CDK v2 (TypeScript) code
 * based on the canvas components and data flows.
 */
export function generateAwsCdkCode(
  nodes: ArchitectureNodeData[],
  edges: ArchitectureEdgeData[]
): string {
  const hasCloudFront = nodes.some((n) => n.id.includes('cloudfront') || n.label.includes('CloudFront'));
  const hasS3 = nodes.some((n) => n.id.includes('s3') || n.label.includes('S3'));
  const hasApiGateway = nodes.some((n) => n.id.includes('api') || n.label.includes('API'));
  const hasLambda = nodes.some((n) => n.id.includes('lambda') || n.label.includes('Lambda'));
  const hasDynamoDB = nodes.some((n) => n.id.includes('dynamodb') || n.label.includes('DynamoDB'));
  const hasBedrock = nodes.some((n) => n.id.includes('bedrock') || n.label.includes('Bedrock'));

  return `import * as cdk from 'aws-cdk-lib';
import { Construct } from 'constructs';
${hasS3 ? "import * as s3 from 'aws-cdk-lib/aws-s3';" : ''}
${hasCloudFront ? "import * as cloudfront from 'aws-cdk-lib/aws-cloudfront';\nimport * as origins from 'aws-cdk-lib/aws-cloudfront-origins';" : ''}
${hasLambda ? "import * as lambda from 'aws-cdk-lib/aws-lambda';" : ''}
${hasApiGateway ? "import * as apigateway from 'aws-cdk-lib/aws-apigateway';" : ''}
${hasDynamoDB ? "import * as dynamodb from 'aws-cdk-lib/aws-dynamodb';" : ''}
${hasBedrock ? "import * as iam from 'aws-cdk-lib/aws-iam';" : ''}

/**
 * Generated by AWS Builder Center Sandbox IaC Synthesizer
 * Architecture: Serverless Edge Stack
 */
export class AwsBuilderInfrastructureStack extends cdk.Stack {
  constructor(scope: Construct, id: string, props?: cdk.StackProps) {
    super(scope, id, props);

${hasS3 ? `    // 1. Amazon S3: Static Web Hosting Bucket with Block Public Access
    const websiteBucket = new s3.Bucket(this, 'PortfolioBucket', {
      blockPublicAccess: s3.BlockPublicAccess.BLOCK_ALL,
      encryption: s3.BucketEncryption.S3_MANAGED,
      enforceSSL: true,
      removalPolicy: cdk.RemovalPolicy.DESTROY,
      autoDeleteObjects: true,
    });\n` : ''}
${hasDynamoDB ? `    // 2. Amazon DynamoDB: Global Visitor Telemetry & Contact Messages
    const telemetryTable = new dynamodb.Table(this, 'TelemetryTable', {
      partitionKey: { name: 'pk', type: dynamodb.AttributeType.STRING },
      sortKey: { name: 'sk', type: dynamodb.AttributeType.STRING },
      billingMode: dynamodb.BillingMode.PAY_PER_REQUEST,
      pointInTimeRecovery: true,
      removalPolicy: cdk.RemovalPolicy.DESTROY,
    });\n` : ''}
${hasLambda ? `    // 3. AWS Lambda: Serverless Backend & AI Orchestrator
    const apiHandler = new lambda.Function(this, 'ApiHandlerFunction', {
      runtime: lambda.Runtime.NODEJS_20_X,
      handler: 'index.handler',
      code: lambda.Code.fromInline(\`
        exports.handler = async (event) => {
          return {
            statusCode: 200,
            headers: { 'Content-Type': 'application/json', 'Access-Control-Allow-Origin': '*' },
            body: JSON.stringify({ message: 'Hello from AWS Builder Lambda!', timestamp: new Date().toISOString() })
          };
        };
      \`),
      environment: {
        ${hasDynamoDB ? "TABLE_NAME: telemetryTable.tableName," : ''}
        REGION: this.region,
      },
      memorySize: 256,
      timeout: cdk.Duration.seconds(10),
    });
${hasDynamoDB ? "    telemetryTable.grantReadWriteData(apiHandler);\n" : ''}` : ''}
${hasBedrock ? `    // 4. Amazon Bedrock IAM Permissions for Claude Foundation Models
    apiHandler.addToRolePolicy(
      new iam.PolicyStatement({
        actions: ['bedrock:InvokeModel', 'bedrock:InvokeModelWithResponseStream'],
        resources: ['arn:aws:bedrock:*::foundation-model/anthropic.claude-3-5-haiku-20241022-v1:0'],
      })
    );\n` : ''}
${hasApiGateway ? `    // 5. Amazon API Gateway: REST Endpoint with CORS
    const restApi = new apigateway.RestApi(this, 'BuilderRestApi', {
      restApiName: 'AWS Builder Center API',
      defaultCorsPreflightOptions: {
        allowOrigins: apigateway.Cors.ALL_ORIGINS,
        allowMethods: apigateway.Cors.ALL_METHODS,
      },
    });
    const apiIntegration = new apigateway.LambdaIntegration(apiHandler);
    restApi.root.addResource('telemetry').addMethod('POST', apiIntegration);\n` : ''}
${hasCloudFront ? `    // 6. Amazon CloudFront: Global Content Delivery Network
    const distribution = new cloudfront.Distribution(this, 'CdnDistribution', {
      defaultBehavior: {
        origin: origins.S3BucketOrigin.withOriginAccessControl(websiteBucket),
        viewerProtocolPolicy: cloudfront.ViewerProtocolPolicy.REDIRECT_TO_HTTPS,
        cachePolicy: cloudfront.CachePolicy.CACHING_OPTIMIZED,
      },
      comment: 'AWS Builder Center Edge CDN',
    });

    new cdk.CfnOutput(this, 'CloudFrontUrl', {
      value: \`https://\${distribution.distributionDomainName}\`,
      description: 'Production Global Edge URL',
    });` : ''}
  }
}
`;
}

/**
 * Generates AWS CloudFormation (YAML) template
 */
export function generateCloudFormationYaml(
  nodes: ArchitectureNodeData[],
  edges: ArchitectureEdgeData[]
): string {
  return `AWSTemplateFormatVersion: '2010-09-09'
Description: AWS Builder Center Stack generated by Visual Architecture Sandbox

Resources:
  WebsiteBucket:
    Type: AWS::S3::Bucket
    Properties:
      BucketEncryption:
        ServerSideEncryptionConfiguration:
          - ServerSideEncryptionByDefault:
              SSEAlgorithm: AES256
      PublicAccessBlockConfiguration:
        BlockPublicAcls: true
        BlockPublicPolicy: true
        IgnorePublicAcls: true
        RestrictPublicBuckets: true

  TelemetryDynamoTable:
    Type: AWS::DynamoDB::Table
    Properties:
      BillingMode: PAY_PER_REQUEST
      AttributeDefinitions:
        - AttributeName: pk
          AttributeType: S
      KeySchema:
        - AttributeName: pk
          KeyType: HASH

  LambdaExecutionRole:
    Type: AWS::IAM::Role
    Properties:
      AssumeRolePolicyDocument:
        Version: '2012-10-17'
        Statement:
          - Effect: Allow
            Principal:
              Service: [lambda.amazonaws.com]
            Action: ['sts:AssumeRole']
      ManagedPolicyArns:
        - arn:aws:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole

  ApiHandlerFunction:
    Type: AWS::Lambda::Function
    Properties:
      Runtime: nodejs20.x
      Role: !GetAtt LambdaExecutionRole.Arn
      Handler: index.handler
      Code:
        ZipFile: |
          exports.handler = async () => ({ statusCode: 200, body: 'OK' });

Outputs:
  BucketName:
    Value: !Ref WebsiteBucket
  TableName:
    Value: !Ref TelemetryDynamoTable
`;
}

